def area(a):
    """
    Вычисляет площадь квадрата по данной стороне.

    Args:
        a (float): сторона квадрата.

    Returns:
        float: площадь квадрата.

    Example:
        >>> area(2)
        4
    """
    return a * a


def perimeter(a):
    """
    Вычисляет периметр квадрата по данной стороне.

    Args:
        a (float): сторона квадрата.

    Returns:
        float: периметр квадрата.

    Example:
        >>> perimeter(2)
        8
    """
    return 4 * a
